<?php
/**
 * One-off generator (NOT runtime) for config/data/comuni_emilia_romagna.php.
 *
 * Source: ISTAT "Elenco comuni italiani"
 *   page: https://www.istat.it/classificazione-e-codifiche/elenco-comuni-italiani/
 *   csv:  https://www.istat.it/storage/codici-unita-amministrative/Elenco-comuni-italiani.csv
 * The file is Windows-1252, ';'-separated. Usage:
 *   php bin/generate-comuni-er.php /path/Elenco-comuni-italiani.csv [YYYY-MM-DD download date]
 * Keeps Codice Regione = 08 (Emilia-Romagna), groups by "Sigla automobilistica"
 * (col 15) and uses "Denominazione in italiano" (col 7).
 */
declare(strict_types=1);

$src = $argv[1] ?? null;
$date = $argv[2] ?? date('Y-m-d');
if (!$src || !is_file($src)) {
    fwrite(STDERR, "Usage: php bin/generate-comuni-er.php <istat.csv> [download-date]\n");
    exit(1);
}
$raw = (string)file_get_contents($src);
$utf8 = mb_convert_encoding($raw, 'UTF-8', 'Windows-1252');
$provinces = ['BO', 'FE', 'FC', 'MO', 'PR', 'PC', 'RA', 'RE', 'RN'];
$out = array_fill_keys($provinces, []);
// Header cells contain embedded newlines inside quotes: parse with str_getcsv on the whole text.
$fh = fopen('php://memory', 'r+');
fwrite($fh, $utf8);
rewind($fh);
while (($row = fgetcsv($fh, 0, ';', '"')) !== false) {
    if (($row[0] ?? '') !== '08') {
        continue;
    }
    $sigla = trim($row[14]);
    $name = trim($row[6]);
    if (!isset($out[$sigla]) || $name === '') {
        fwrite(STDERR, "Unexpected row: $sigla / $name\n");
        exit(1);
    }
    $out[$sigla][] = $name;
}
$total = 0;
foreach ($out as $sigla => &$list) {
    $list = array_values(array_unique($list));
    $collator = new Collator('it_IT');
    $collator->sort($list);
    $total += count($list);
}
unset($list);
$body = "[\n";
foreach ($out as $sigla => $list) {
    $body .= "  '$sigla' => [\n";
    foreach ($list as $name) {
        $body .= "    '" . str_replace(['\\', "'"], ['\\\\', "\\'"], $name) . "',\n";
    }
    $body .= "  ],\n";
}
$body .= ']';
$header = "<?php\n/**\n * Comuni dell'Emilia-Romagna per sigla di provincia.\n * Generated by bin/generate-comuni-er.php - DO NOT EDIT BY HAND.\n * Source: ISTAT, Elenco comuni italiani\n *   https://www.istat.it/storage/codici-unita-amministrative/Elenco-comuni-italiani.csv\n * Downloaded: $date. Total comuni: $total.\n */\ndeclare(strict_types=1);\n\nreturn ";
$php = $header . $body . ";\n";
if (!mb_check_encoding($php, 'UTF-8')) {
    fwrite(STDERR, "Output is not valid UTF-8\n");
    exit(1);
}
file_put_contents(__DIR__ . '/../config/data/comuni_emilia_romagna.php', $php);
echo "Wrote $total comuni\n";
foreach ($out as $k => $v) {
    echo "$k " . count($v) . "\n";
}
